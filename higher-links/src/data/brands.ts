/** Stable pseudo-random review count so placeholder numbers don't change between builds. */
function placeholderReviews(slug: string, links: number) {
  let h = 2166136261;
  for (const ch of slug) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return 60 + (Math.abs(h) % 900) + links * 7;
}

function productUrl(brand: string, product: string) {
  return `https://www.tiktok.com/search?q=${encodeURIComponent(`${brand} ${product}`)}`;
}

export const brands: Brand[] = SEED.map((s) => {
  const products: Product[] = (s.products ?? []).map(([name, price, commission], i) => ({
    id: `${s.slug}-${i + 1}`,
    name,
    image: "",
    price,
    commission,
    url: productUrl(s.name, name),
  }));
  return {
    slug: s.slug,
    name: s.name,
    logo: `/logos/${s.slug}.png`,
    commission: s.commission,
    rating: s.rating,
    reviews: s.reviews ?? placeholderReviews(s.slug, s.links),
    links: s.links,
    hot: s.hot,
    comingSoon: s.comingSoon,
    category: s.category,
    campaignTitle: s.campaignTitle ?? `${s.name.toUpperCase()} CREATOR CAMPAIGN`,
    accent: s.accent,
    products,
  };
});

export function getBrand(slug: string) {
  return brands.find((b) => b.slug === slug);
}
